"use client";
import { useRef, useState, useTransition } from "react";
import { useTranslations } from "next-intl";
import { Input } from "@/components/arc/input/input";
import { Alert } from "@/components/arc/alert/alert";
import { WriteButton } from "@/components/pwa/write-button";
import { enrollAdminMfa, verifyAdminMfa } from "../mfa-actions";
export function MfaForm({
  factorId,
  next,
}: {
  factorId?: string;
  next?: string;
}) {
  const t = useTranslations("auth"),
    [pending, start] = useTransition(),
    [error, setError] = useState(""),
    [factor, setFactor] = useState(factorId ?? ""),
    [secret, setSecret] = useState(""),
    [qr, setQr] = useState(""),
    [code, setCode] = useState(""),
    input = useRef<HTMLInputElement>(null);
  return (
    <div className="stack">
      <Alert
        open={!!error}
        tone="danger"
        title={t.has(error) ? t(error) : t("unavailable")}
      />
      {!factor ? (
        <>
          <p>{t("mfaEnrollHint")}</p>
          <WriteButton
            loading={pending}
            disabled={pending}
            size="lg"
            onClick={() =>
              start(async () => {
                setError("");
                try {
                  const result = await enrollAdminMfa();
                  if (!result.ok) setError(result.error);
                  else {
                    setFactor(result.data.id);
                    setSecret(result.data.secret);
                    setQr(result.data.qr);
                  }
                } catch {
                  setError("unavailable");
                }
              })
            }
          >
            {t("mfaStart")}
          </WriteButton>
        </>
      ) : (
        <>
          {qr && (
            <>
              <p>{t("mfaScan")}</p>
              {/* QR is generated by authenticated Supabase Auth. It stays in memory only. */}
              {/* eslint-disable-next-line @next/next/no-img-element */}
              <img
                className="mfa-qr"
                src={
                  qr.startsWith("data:")
                    ? qr
                    : `data:image/svg+xml;utf8,${encodeURIComponent(qr)}`
                }
                alt={t("mfaQrAlt")}
                width={240}
                height={240}
              />
              <Input
                label={t("mfaSecret")}
                value={secret}
                readOnly
                autoComplete="off"
              />
              <p>{t("mfaSecretHint")}</p>
            </>
          )}
          <form
            className="stack"
            onSubmit={(event) => {
              event.preventDefault();
              setError("");
              if (!/^\d{6}$/.test(code)) {
                setError("mfaInvalidCode");
                input.current?.focus();
                return;
              }
              start(async () => {
                try {
                  const result = await verifyAdminMfa({
                    id: factor,
                    code,
                    next,
                  });
                  if (!result.ok) {
                    setError(result.error);
                    input.current?.focus();
                  }
                } catch {
                  setError("unavailable");
                }
              });
            }}
          >
            <Input
              ref={input}
              label={t("mfaCode")}
              name="code"
              value={code}
              onChange={(e) => setCode(e.target.value)}
              inputMode="numeric"
              autoComplete="one-time-code"
              maxLength={6}
              required
              error={error === "mfaInvalidCode" ? t(error) : undefined}
            />
            <WriteButton
              type="submit"
              loading={pending}
              disabled={pending}
              size="lg"
            >
              {t("mfaVerify")}
            </WriteButton>
          </form>
        </>
      )}
    </div>
  );
}
